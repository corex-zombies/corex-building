CREATE TABLE IF NOT EXISTS corex_buildings (
    id VARCHAR(32) NOT NULL PRIMARY KEY,
    owner VARCHAR(128) NOT NULL,
    bucket INT UNSIGNED NOT NULL DEFAULT 0,
    payload LONGTEXT NOT NULL,
    password_hash VARCHAR(160) NULL,
    revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    INDEX owner_bucket (owner, bucket)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS corex_build_operations (
    id VARCHAR(32) NOT NULL PRIMARY KEY,
    status VARCHAR(16) NOT NULL,
    payload LONGTEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX pending_operations (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
